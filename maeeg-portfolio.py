class AttentionPooling(nn.Module):
    def __init__(self, d_model):
        super().__init__()
        self.attention_weight = nn.Linear(d_model, 1)#dmodel,1
    def forward(self, x):
        #x:(B, SeqLen, d_model)
        scores  = self.attention_weight(x)
        weights = torch.softmax(scores, dim=1)
        output = (x * weights).sum(dim=1)#(B, SeqLen, 1)
        return output  #(B, d_model)

class GatedAttentionPooling(nn.Module):
    def __init__(self, d_model):
        super().__init__()
        #特徴抽出 (Tanh)
        self.linear_v = nn.Linear(d_model, d_model)
        #ゲート(Sigmoid) でどれくらい通すか決める
        self.linear_u = nn.Linear(d_model, d_model)
        #最終的に1つのスコアにする重
        self.linear_w = nn.Linear(d_model, 1)

    def forward(self, x):
        #x: (Batch, SeqLen, d_model)
        #1. ゲートメカニズム
        #vは特徴変換uはゲート開閉
        v = torch.tanh(self.linear_v(x))
        u = torch.sigmoid(self.linear_u(x))
        gated_features = v * u
        #2. スコア計算
        #ゲートを通った特徴をもとにスコアを出す
        scores = self.linear_w(gated_features) #(B, SeqLen, 1)

        weights = torch.softmax(scores, dim=1)
        output = (x * weights).sum(dim=1)
        return output


