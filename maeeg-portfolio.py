def objective(trial):
    # --- A. Optunaに探索させたいハイパラを登録 ---

    # 1. 学習率 (1e-5 から 1e-2 の間で対数的に探す)
    lr = trial.suggest_float("lr", 1e-5, 1e-2, log=True)

    # 2. バッチサイズ (いくつか候補を挙げる)
    batch_size = trial.suggest_categorical("batch_size", [64, 128, 256])

    # 3. OptimizerのWeight Decay (過学習の抑え具合)
    weight_decay = trial.suggest_float("weight_decay", 1e-5, 1e-1, log=True)

    # 4. Mixupの強さ (alpha)
    mixup_alpha = trial.suggest_float("mixup_alpha", 0.1, 1.0)

    # ----------------------------------------
    # データローダーの準備 (バッチサイズが変わるためここで作る)
    # ----------------------------------------
    train_set = ThingsEEGDataset("train")
    train_loader = torch.utils.data.DataLoader(
        train_set, batch_size=batch_size, shuffle=True, num_workers=2
    )
    val_set = ThingsEEGDataset("val")
    val_loader = torch.utils.data.DataLoader(
        val_set, batch_size=batch_size, shuffle=False, num_workers=2
    )

    # ----------------------------------------
    # モデルとOptimizerの準備
    # ----------------------------------------
    model = EEGNetHybrid().to("cuda")

    # 提案された lr と weight_decay を使う
    optimizer = optim.AdamW(model.parameters(), lr=lr, weight_decay=weight_decay)

    # Schedulerもハイパラに合わせて調整してもいいが、一旦固定
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=15) # 探索時は短めでOK
    criterion = nn.CrossEntropyLoss()

    # ----------------------------------------
    # 学習ループ (高速化のためエポック数は減らす)
    # ----------------------------------------
    n_epochs_pruning = 15 # ハイパラ探索用なので、本番(60)より短くする

    for epoch in range(n_epochs_pruning):
        model.train()
        for X, y, _ in train_loader:
            X, y = X.to("cuda"), y.to("cuda")

            # 提案された mixup_alpha を使う
            mixed_x, y_a, y_b, lam = mixup_data(X, y, alpha=mixup_alpha)

            preds = model(mixed_x)
            loss = lam * criterion(preds, y_a) + (1 - lam) * criterion(preds, y_b)

            optimizer.zero_grad()
            loss.backward()
            optimizer.step()

        scheduler.step()

        # --- 検証 (Pruningの判定) ---
        model.eval()
        val_acc_list = []
        with torch.no_grad():
            for X, y, _ in val_loader:
                X, y = X.to("cuda"), y.to("cuda")
                preds = model(X)
                acc = (preds.argmax(dim=-1) == y).float().mean().item()
                val_acc_list.append(acc)

        avg_val_acc = np.mean(val_acc_list)

        # --- B. Pruning (見込みのない試行の切り捨て) ---
        # Optunaに現在の精度を報告
        trial.report(avg_val_acc, epoch)

        # 「この学習率じゃ全然ダメだわ」と判断されたら、強制終了して次の試行へ
        if trial.should_prune():
            raise optuna.TrialPruned()

    # 最終的な検証精度を返す (これを最大化するのが目的)
    return avg_val_acc

