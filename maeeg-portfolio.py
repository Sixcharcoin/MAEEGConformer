class ThingsEEGDataset(torch.utils.data.Dataset):
    def __init__(self, split: str) -> None:
        super().__init__()

        assert split in ["train", "val", "test"], f"Invalid split: {split}"
        self.split = split
        self.num_classes = 5
        self.num_subjects = 10

        self.X = np.load(f"data/{split}/eeg.npy")
        self.X = torch.from_numpy(self.X).to(torch.float32)
        self.subject_idxs = np.load(f"data/{split}/subject_idxs.npy")
        self.subject_idxs = torch.from_numpy(self.subject_idxs)

        if split in ["train", "val"]:
            self.y = np.load(f"data/{split}/labels.npy")
            self.y = torch.from_numpy(self.y)

        print(f"EEG: {self.X.shape}, labels: {self.y.shape if hasattr(self, 'y') else None}, subject indices: {self.subject_idxs.shape}")

    def __len__(self) -> int:
        return len(self.X)

    '''
    データ拡張
    どのモデルでも精度が上がらない
    改善方針
    ＞適当に全部掛けたらデータが破壊されすぎて学習の妨げになってるかもしれないと仮説を立てたので、確率p_augでどれか一つを選ぶようにｓる
    '''
    def __getitem__(self, i):
        x = self.X[i]

        #mean = x.mean(dim=1, keepdim=True)
        #>>>サンプル単位での正規化に変更
        mean = x.mean()
        #std = x.std(dim=1, keepdim=True)
        std = x.std()
        x = (x-mean) / (std + 1e-6)

        if self.split == 'train':

            p_aug = 0.7
            if torch.rand(1) < p_aug:
                aug_type = torch.randint(0, 5, (1,)).item()
#noise
                if aug_type == 0:
                    noise = torch.randn_like(x) * 0.05
                    x = x+noise
#shift
                elif aug_type == 1:
                    shift = torch.randint(-3, 3, (1,)).item()
                    x = torch.roll(x, shifts=shift, dims=1)
#dropout channel
                elif aug_type == 2:
                    num_drop = torch.randint(1, 4, (1,)).item()
                    drop_idx = torch.randperm(x.shape[0])[:num_drop]
                    x[drop_idx] = 0
#なんか間違えて2回やってる

                elif aug_type == 3:
                    shift = torch.randint(-3, 3, (1,)).item()
                    x = torch.roll(x, shifts=shift, dims=1)

#time mask
                elif aug_type == 4:
                    t_start = torch.randint(0, 85, (1,)).item()
                    t_len = torch.randint(5, 15, (1,)).item()
                    x[:, t_start:t_start+t_len] = 0
#scaling
                elif aug_type == 5:
                    scale = torch.empty(1).uniform_(0.8, 1.2)
                    x = x * scale

        if hasattr(self, "y"):
            return x, self.y[i], self.subject_idxs[i]
        else:
            return x, self.subject_idxs[i]

    @property
    def num_channels(self) -> int:
        return self.X.shape[1]

    @property
    def seq_len(self) -> int:
        return self.X.shape[2]

