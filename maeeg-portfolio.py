class Swish(nn.Module):
    def forward(self, x):
        return x * torch.sigmoid(x)

class ConformerBlock(nn.Module):
    def __init__(self, d_model=64, n_heads=4, conv_kernel_size=15, dropout=0.1):
        super().__init__()
        #Feed Forward Module 1
        self.ff1 = nn.Sequential(
            nn.LayerNorm(d_model),
            nn.Linear(d_model, d_model * 4),
            Swish(),
            nn.Dropout(dropout),
            nn.Linear(d_model * 4, d_model),
            nn.Dropout(dropout)
        )
        #Multi-Head Self-Attention
        self.attn_norm = nn.LayerNorm(d_model)
        self.attn = nn.MultiheadAttention(d_model, n_heads, dropout=dropout, batch_first=True)
        self.attn_dropout = nn.Dropout(dropout)

        #Convolution Module
        self.conv_norm = nn.LayerNorm(d_model)

        self.conv = nn.Sequential(
            #Pointwise Conv
            nn.LayerNorm(d_model),
            nn.Conv1d(d_model, d_model * 2, kernel_size=1),
            nn.GLU(dim=1),  #d_model * 2 >> d_model
            #Depthwise Conv
            nn.Conv1d(
                d_model,
                d_model,
                kernel_size=conv_kernel_size,
                padding=conv_kernel_size // 2, groups=d_model),
            nn.BatchNorm1d(d_model),
            Swish(),
            #Pointwise Conv
            nn.Conv1d(d_model, d_model, kernel_size=1),
            nn.Dropout(dropout)
        )

        #Feed Forward Module 2
        self.ff2 = nn.Sequential(
            nn.LayerNorm(d_model),
            nn.Linear(d_model, d_model * 4),
            Swish(),
            nn.Dropout(dropout),
            nn.Linear(d_model * 4, d_model),
            nn.Dropout(dropout)
        )

        self.final_norm = nn.LayerNorm(d_model)

    def forward(self, x):
        #x(Batch, Time, Dim)
        #Feed Forward 1 (half residual)
        x = x + 0.5 * self.ff1(x)

        #Self-Attention
        x_norm = self.attn_norm(x)
        attn_out, _ = self.attn(x_norm, x_norm, x_norm)
        x = x + self.attn_dropout(attn_out)
        #Convolution
        x_norm = self.conv_norm(x)
        x_conv = x_norm.transpose(1, 2)  # (B, D, T) for Conv1d
        x_conv = self.conv(x_conv)
        x_conv = x_conv.transpose(1, 2)  # (B, T, D)
        x = x + x_conv
        #Feed Forward 2 (half residual)
        x = x + 0.5 * self.ff2(x)

        return self.final_norm(x)

class ConformerBlockV2(nn.Module):
    def __init__(self, d_model=64, n_heads=4, conv_kernel_size=31, dropout=0.1):
        super().__init__()

        # Feed Forward Module 1
        self.ffn1 = nn.Sequential(
            nn.LayerNorm(d_model),
            nn.Linear(d_model, d_model * 4),
            Swish(),
            nn.Dropout(dropout),
            nn.Linear(d_model * 4, d_model),
            nn.Dropout(dropout),
        )

        # Multi-Head Self-Attention
        self.attn_norm = nn.LayerNorm(d_model)
        self.self_attn = nn.MultiheadAttention(
            embed_dim=d_model, num_heads=n_heads,
            dropout=dropout, batch_first=True
        )
        self.attn_dropout = nn.Dropout(dropout)

        # Convolution Module
        self.conv_norm = nn.LayerNorm(d_model)
        self.pw_conv1 = nn.Conv1d(d_model, d_model * 2, kernel_size=1)
        self.glu = nn.GLU(dim=1)
        self.dw_conv = nn.Conv1d(
            d_model, d_model,
            kernel_size=conv_kernel_size,
            padding=(conv_kernel_size - 1) // 2,
            groups=d_model,
        )
        self.dw_norm = nn.LayerNorm(d_model)
        self.dw_act = Swish()
        self.pw_conv2 = nn.Conv1d(d_model, d_model, kernel_size=1)
        self.conv_dropout = nn.Dropout(dropout)

        # Feed Forward Module 2
        self.ffn2 = nn.Sequential(
            nn.LayerNorm(d_model),
            nn.Linear(d_model, d_model * 4),
            Swish(),
            nn.Dropout(dropout),
            nn.Linear(d_model * 4, d_model),
            nn.Dropout(dropout),
        )

        self.final_norm = nn.LayerNorm(d_model)

    def forward(self, x):
        # x: (B, T, D)
        #Feed Forward 1 (half-step)
        x = x + 0.5 * self.ffn1(x)

        #Self-Attention
        x_norm = self.attn_norm(x)
        attn_out, _ = self.self_attn(x_norm, x_norm, x_norm)  # (B, T, D)
        x = x + self.attn_dropout(attn_out)

        #Convolution Module
        residual = x
        x_norm = self.conv_norm(x)              # (B, T, D)
        x_conv = x_norm.transpose(1, 2)         # (B, D, T)

        x_conv = self.pw_conv1(x_conv)          # (B, 2D, T)
        x_conv = self.glu(x_conv)               # (B, D, T)

        x_conv = self.dw_conv(x_conv)           # (B, D, T)
        x_conv = x_conv.transpose(1, 2)         # (B, T, D)
        x_conv = self.dw_norm(x_conv)
        x_conv = self.dw_act(x_conv)
        x_conv = x_conv.transpose(1, 2)         # (B, D, T)

        x_conv = self.pw_conv2(x_conv)          # (B, D, T)
        x_conv = x_conv.transpose(1, 2)         # (B, T, D)

        x = residual + self.conv_dropout(x_conv)

        #Feed Forward 2 (half-step)
        x = x + 0.5 * self.ffn2(x)

        return self.final_norm(x)

