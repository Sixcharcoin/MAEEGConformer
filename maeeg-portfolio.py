class MAEEG_Pretrain(nn.Module):
    def __init__(self, in_channels=17, time_steps=100, embed_dim=64, mask_ratio=0.5):#.75>.5
        super().__init__()
        self.mask_ratio = mask_ratio
        self.time_steps = time_steps

        self.patch_embed = nn.Sequential(
            nn.Conv1d(in_channels, embed_dim, kernel_size=1),
            nn.BatchNorm1d(embed_dim),
            nn.GELU()
        )

        self.pos_encoder = PositionalEncodingV2(embed_dim, max_len=time_steps)

        encoder_layer = nn.TransformerEncoderLayer(
            d_model=embed_dim, nhead=4, dim_feedforward=768,
            batch_first=True, dropout=0.1
        )
        self.transformer_encoder = nn.TransformerEncoder(encoder_layer, num_layers=2)

        decoder_layer = nn.TransformerEncoderLayer(
            d_model=embed_dim, nhead=4, dim_feedforward=384,
            batch_first=True, dropout=0.1
        )
        self.transformer_decoder = nn.TransformerEncoder(decoder_layer, num_layers=1)

        self.output_head = nn.Linear(embed_dim, in_channels)

        self.mask_token = nn.Parameter(torch.zeros(1, 1, embed_dim))

        self._init_weights()

    def _init_weights(self):

        for m in self.modules():
            if isinstance(m, nn.Linear):
                nn.init.xavier_uniform_(m.weight)
                if m.bias is not None:
                    nn.init.constant_(m.bias, 0)
            elif isinstance(m, nn.LayerNorm):
                nn.init.constant_(m.bias, 0)
                nn.init.constant_(m.weight, 1.0)

    #マスキング処理
    def random_masking(self, x):

        N, L, D = x.shape

        len_keep = int(L * (1 - self.mask_ratio))

        noise = torch.rand(N, L, device=x.device)

        ids_shuffle = torch.argsort(noise, dim=1)

        ids_restore = torch.argsort(ids_shuffle, dim=1)

        ids_keep = ids_shuffle[:, :len_keep]

        x_masked = torch.gather(x, dim=1, index=ids_keep.unsqueeze(-1).repeat(1, 1, D))

        #マスク生成 (Loss計算用で 隠した部分を1にする)
        mask = torch.ones([N, L], device=x.device)
        mask[:, :len_keep] = 0
        mask = torch.gather(mask, dim=1, index=ids_restore)

        return x_masked, mask, ids_restore


    def forward(self, x):

        feat = self.patch_embed(x)

        feat = feat.transpose(1, 2)

        feat = feat + self.pos_encoder(torch.zeros_like(feat))

        latent, mask, ids_restore = self.random_masking(feat)

        latent = self.transformer_encoder(latent)

        mask_tokens = self.mask_token.repeat(feat.shape[0], ids_restore.shape[1] - latent.shape[1], 1)

        x_ = torch.cat([latent, mask_tokens], dim=1)

        x_reconstructed_input = torch.gather(x_, dim=1, index=ids_restore.unsqueeze(-1).repeat(1, 1, feat.shape[2]))

        x_reconstructed_input = x_reconstructed_input + self.pos_encoder.pos_embed

        decoded = self.transformer_decoder(x_reconstructed_input)

        pred = self.output_head(decoded)
        pred = pred.transpose(1, 2)

        return pred, mask

